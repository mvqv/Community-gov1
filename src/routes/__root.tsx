function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  useEffect(() => {
    if (typeof window === "undefined") return;
    try {
      if (window.history.scrollRestoration) {
        window.history.scrollRestoration = "manual";
      }
    } catch {}
    // Strip any hash from the URL so the browser doesn't auto-scroll to #section on refresh.
    if (window.location.hash) {
      try {
        window.history.replaceState(
          null,
          "",
          window.location.pathname + window.location.search,
        );
      } catch {}
    }
    window.scrollTo(0, 0);
    const raf1 = window.requestAnimationFrame(() => {
      window.scrollTo(0, 0);
      const raf2 = window.requestAnimationFrame(() => window.scrollTo(0, 0));
      (window as any).__scrollRaf2 = raf2;
    });
    return () => {
      window.cancelAnimationFrame(raf1);
      if ((window as any).__scrollRaf2) window.cancelAnimationFrame((window as any).__scrollRaf2);
    };
  }, []);

  return (
    <QueryClientProvider client={queryClient}>
      <I18nProvider>
        {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
        <Outlet />
      </I18nProvider>
    </QueryClientProvider>
  );
}
